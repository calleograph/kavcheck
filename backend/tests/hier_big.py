"""Синтетическая выгрузка адресной книги: 1 000+ сотрудников и 40 подразделений с известными «ловушками» (все данные вымышленные).
Считаются контрольные числа: `EXPECT` — что должны показать отчёты."""
import random

from tests.hier_data import DOMAIN, rec

WORDS = ["Закупок", "Продаж", "Логистики", "Разработки", "Поддержки", "Аналитики", "Безопасности", "Качества", "Планирования", "Контроля", "Сервиса", "Обучения", "Снабжения", "Маркетинга", "Проектов", "Эксплуатации",
         "Архива", "Договоров", "Тендеров", "Учёта", "Расчётов", "Мониторинга", "Интеграции", "Тестирования", "Данных", "Платформ", "Сетей", "Склада", "Транспорта", "Ремонта", "Охраны", "Отчётности", "Бюджета", "Страхования",
         "Рекламы", "Партнёров", "Внедрения", "Сопровождения", "Хранения", "Инноваций"]
FAM = ["Орлов", "Лебедев", "Ершов", "Тихонов", "Галкин", "Фролов", "Савин", "Зимин", "Нестеров", "Хохлов", "Ильин", "Жуков", "Беляев", "Мельников", "Соколов", "Кузнецов", "Волков", "Попов", "Новиков", "Морозов"]
NAM = ["Олег Олегович", "Игорь Игоревич", "Роман Романович", "Денис Денисович", "Павел Павлович", "Кирилл Кириллович", "Борис Борисович", "Тимур Тимурович", "Антон Антонович", "Глеб Глебович"]


def big_records(seed: int = 7) -> tuple[list[dict], dict]:
    rnd = random.Random(seed)
    out: list[dict] = []
    n = [0]
    used: set[str] = set()

    def user(title, dept, boss=None, name=None, **kw):
        n[0] += 1
        e = f"u{n[0]:05d}@{DOMAIN}"
        nm = name or f"{rnd.choice(FAM)}{n[0]} {rnd.choice(NAM)}"
        used.add(nm)
        out.append(rec(nm, e, title, dept, boss[0] if boss else kw.pop("mgr", ""), boss[1] if boss else kw.pop("mgr_email", ""), **kw))
        return nm, e

    ceo = user("Генеральный директор", "Руководство")
    out[-1]["Manager"], out[-1]["ManagerEmail"] = ceo
    dirs = [user(f"Директор направления {i}", f"Дирекция {i}", ceo) for i in range(8)]
    dn = [f"Отдел {w}" for w in WORDS]
    heads = [user(f"Начальник отдела {w}", dn[i], dirs[i % 8]) for i, w in enumerate(WORDS)]
    people = 0
    for d in range(40):
        for k in range(24 if d else 70):                            # отдел 0 — большая плоская группа
            user(rnd.choice(["Специалист", "Инженер", "Аналитик", "Менеджер"]), dn[d], heads[d])
            people += 1
    # варианты написаний отдела продаж (d=1): не объединяются сами
    for k in range(6):
        user("Менеджер", "Департамент продаж", heads[1])
    for k in range(4):
        user("Менеджер", "отдел  продаж ", heads[1])
    # подчинение руководителю другого подразделения: 12 человек отдела 5 у начальника отдела 6, один из отдела 7 у начальника 8
    for k in range(12):
        user("Специалист", dn[5], heads[6])
    user("Инженер", dn[7], heads[8])
    # пустое подразделение (подставится от руководителя), пустая должность, нет руководителя
    for k in range(30):
        user("Специалист", "", heads[10])
    for k in range(20):
        user("", dn[11], heads[11])
    for k in range(15):
        user("Аналитик", dn[12], None)
    # цикл
    a, b = user("Аналитик", dn[13], None, mgr="x"), user("Аналитик", dn[13], None, mgr="y")
    out[-2]["Manager"], out[-2]["ManagerEmail"] = b
    out[-1]["Manager"], out[-1]["ManagerEmail"] = a
    # одинаковые ФИО у разных людей; повтор адреса
    user("Бухгалтер", dn[14], heads[14], name="Тестов Семён Семёнович")
    user("Бухгалтер", dn[15], heads[15], name="Тестов Семён Семёнович")
    out.append(rec("Повторов Адрес Адресович", out[50]["Email"], "Менеджер", dn[3], heads[3][0], heads[3][1]))
    # двое руководителей с одним ФИО и трое подчинённых только по тексту
    user("Начальник группы", dn[16], heads[16], name="Руководов Пётр Петрович")
    user("Начальник группы", dn[17], heads[17], name="Руководов Пётр Петрович")
    for k in range(3):
        user("Специалист", dn[18], None, mgr="Руководов Пётр Петрович")
    # неруководящая должность с подчинёнными и руководящая без подчинённых
    st = user("Стажёр", dn[19], heads[19])
    for k in range(2):
        user("Специалист", dn[19], st)
    user("Директор по развитию", dn[20], heads[20])
    # служебные, внешние, пустые
    for k in range(10):
        n[0] += 1
        out.append(rec(f"Поддержка {k}", f"support{k:02d}@{DOMAIN}", "служебная запись", "", "", ""))
    for k in range(25):
        n[0] += 1
        out.append(rec(f"{FAM[k]} Внешний {NAM[k]}" if k < 3 else f"Контакт {k}", f"ext{k}@partner.example", "Менеджер", "Партнёр", "", ""))
    for k in range(30):
        n[0] += 1
        out.append(rec(f"{FAM[k % 20]}ский Иван Иванович" if k < 5 else f"Пустышкин{k} Иван Иванович", f"empty{k}@{DOMAIN}", "", "", "", ""))
    rnd.shuffle(out)
    return out, {"raw": len(out), "external": 25, "service": 10, "empty": 30, "dup": 1}
